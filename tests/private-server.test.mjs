import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { once } from "node:events";
import { createApp } from "../private/server.mjs";

test("all pages require account login; invited member and admin roles control the private catalog", async t => {
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),"tgl-private-"));
 const {server,db}=createApp({inviteCode:"ci-test-invitation-code-unpublished",dbPath:path.join(dir,"test.sqlite")});
 server.listen(0,"127.0.0.1");
 await once(server,"listening");
 t.after(async()=>{await new Promise((resolve,reject)=>server.close(e=>e?reject(e):resolve()));db.close();fs.rmSync(dir,{recursive:true,force:true});});
 const base="http://127.0.0.1:"+server.address().port;
 const req=(route,options={})=>fetch(base+route,{redirect:"manual",...options});
 const post=(route,p,cookie="")=>req(route,{method:"POST",headers:{"Content-Type":"application/x-www-form-urlencoded",...(cookie?{Cookie:cookie}:{})},body:new URLSearchParams(p)});
 let r=await req("/");
 assert.equal(r.status,303);assert.equal(r.headers.get("location"),"/login");
 r=await req("/catalog");assert.equal(r.status,303);
 r=await req("/styles.css");assert.equal(r.status,303);
 r=await req("/login");assert.equal(r.status,200);
 assert.match(await r.text(),/Welcome back/);
 r=await post("/register",{email:"member@example.com",password:"correct-long-password-123",invite:"incorrect"});
 assert.equal(r.status,400);
 r=await post("/register",{email:"member@example.com",password:"correct-long-password-123",invite:"ci-test-invitation-code-unpublished"});
 assert.equal(r.status,303);
 r=await post("/login",{email:"member@example.com",password:"wrong-password-123"});
 assert.equal(r.status,401);
 r=await post("/login",{email:"member@example.com",password:"correct-long-password-123"});
 assert.equal(r.status,303);
 const cookie=r.headers.get("set-cookie").split(";")[0];
 assert.ok(cookie.startsWith("tgl_session="));
 assert.match(r.headers.get("set-cookie"),/HttpOnly/);
 assert.match(r.headers.get("set-cookie"),/SameSite=Strict/);
 r=await req("/",{headers:{Cookie:cookie}});assert.equal(r.status,200);
 const home=await r.text();
 assert.match(home,/THE GOOD STUFF/);
 assert.match(home,/Internal catalog/);
 r=await req("/catalog",{headers:{Cookie:cookie}});assert.equal(r.status,200);
 assert.match(await r.text(),/Catalog concepts/);
 r=await req("/admin",{headers:{Cookie:cookie}});assert.equal(r.status,403);
 r=await post("/admin/products",{csrf:"invalid",sku:"TEST-1",name:"Test Item",category:"Lifestyle"},cookie);
 assert.equal(r.status,403);
 db.prepare("UPDATE users SET role='admin' WHERE email=?").run("member@example.com");
 r=await req("/admin",{headers:{Cookie:cookie}});assert.equal(r.status,200);
 let html=await r.text();
 const csrf=html.match(/name="csrf" value="([^"]+)"/)?.[1];
 assert.ok(csrf,"Admin page must include CSRF field");
 r=await post("/admin/products",{csrf,sku:"TEST-1",name:"Demo Accessory",category:"Lifestyle"},cookie);
 assert.equal(r.status,303);
 const id=db.prepare("SELECT id FROM products WHERE sku=?").get("TEST-1").id;
 r=await post("/admin/stock",{csrf,product_id:String(id),delta:"10",reason:"Internal sample stock"},cookie);
 assert.equal(r.status,303);
 assert.equal(db.prepare("SELECT SUM(delta) qty FROM movements WHERE product_id=?").get(id).qty,10);
 r=await post("/admin/stock",{csrf,product_id:String(id),delta:"-11",reason:"Oversell negative attempt"},cookie);
 assert.equal(r.status,400);
 assert.equal(db.prepare("SELECT COUNT(*) count FROM movements WHERE product_id=?").get(id).count,1);
 r=await req("/catalog",{headers:{Cookie:cookie}});html=await r.text();
 assert.match(html,/Demo Accessory/);
 assert.doesNotMatch(html,/checkout|buy now|purchase now/i);
 r=await post("/logout",{csrf},cookie);
 assert.equal(r.status,303);
 r=await req("/",{headers:{Cookie:cookie}});
 assert.equal(r.status,303,"Log out must revoke session on the server");
});
