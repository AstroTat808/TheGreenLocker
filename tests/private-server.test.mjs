import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { once } from "node:events";
import { randomBytes } from "node:crypto";
import { createApp } from "../private/server.mjs";
import { totpAt } from "../private/security.mjs";

test("server-enforced preview: invited verification, member access, admin MFA, inventory and logout",async t=>{
 const originalKey=process.env.TGL_MFA_ENCRYPTION_KEY;
 process.env.TGL_MFA_ENCRYPTION_KEY=randomBytes(32).toString("base64");
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),"tgl-auth-"));
 const messages=[];
 const {server,db}=createApp({inviteCode:"ci-test-invitation-code-unpublished",dbPath:path.join(dir,"test.sqlite"),publicOrigin:"http://127.0.0.1:4174",mailSender:async message=>messages.push(message)});
 server.listen(0,"127.0.0.1");
 await once(server,"listening");
 t.after(async()=>{
   await new Promise((resolve,reject)=>server.close(e=>e?reject(e):resolve()));
   db.close();fs.rmSync(dir,{recursive:true,force:true});
   if(originalKey===undefined)delete process.env.TGL_MFA_ENCRYPTION_KEY;else process.env.TGL_MFA_ENCRYPTION_KEY=originalKey;
 });
 const base="http://127.0.0.1:"+server.address().port;
 const req=(url,options={})=>fetch(base+url,{redirect:"manual",...options});
 const post=(url,body,cookie="")=>req(url,{method:"POST",headers:{"Content-Type":"application/x-www-form-urlencoded",...(cookie?{Cookie:cookie}:{})},body:new URLSearchParams(body)});
 let response=await req("/");
 assert.equal(response.status,303);assert.equal(response.headers.get("location"),"/login");
 response=await req("/catalog");assert.equal(response.status,303);
 response=await req("/styles.css");assert.equal(response.status,303);
 response=await req("/assets/shield-logo.webp");assert.equal(response.status,303,"Private shield asset requires member login.");
 response=await req("/locker-motion.js");assert.equal(response.status,303,"Selector animation requires member login.");
 response=await req("/vault-entry.js");assert.equal(response.status,303,"Vault entrance script requires member login.");
 response=await req("/logo");assert.equal(response.status,200);
 assert.equal(response.headers.get("content-type"),"image/webp");
 let mark=Buffer.from(await response.arrayBuffer());
 assert.equal(mark.subarray(0,4).toString("ascii"),"RIFF");
 assert.equal(mark.subarray(8,12).toString("ascii"),"WEBP");
 response=await req("/favicon.ico");assert.equal(response.status,200);
 assert.equal(response.headers.get("content-type"),"image/png");
 mark=Buffer.from(await response.arrayBuffer());
 assert.equal(mark.subarray(0,8).toString("hex"),"89504e470d0a1a0a");
 response=await post("/register",{email:"member@example.com",password:"correct-long-password-123",invite:"wrong"});
 assert.equal(response.status,400);
 response=await post("/register",{email:"member@example.com",password:"correct-long-password-123",invite:"ci-test-invitation-code-unpublished"});
 assert.equal(response.status,303);
 assert.equal(response.headers.get("location"),"/check-email");
 response=await post("/login",{email:"member@example.com",password:"correct-long-password-123"});
 assert.equal(response.status,403,"Unverified accounts cannot log in.");
 assert.equal(messages.length,1);
 const token=new URL(messages[0].text.match(/https?:\/\/[^\s]+/)[0]).searchParams.get("token");
 assert.ok(token);
 response=await req("/verify-email?token="+encodeURIComponent(token));assert.equal(response.status,200);
 response=await post("/verify-email",{token});assert.equal(response.status,200);
 response=await post("/verify-email",{token});assert.equal(response.status,400,"Verification links are single-use.");
 response=await post("/login",{email:"member@example.com",password:"wrong-password-123"});
 assert.equal(response.status,401);
 response=await post("/login",{email:"member@example.com",password:"correct-long-password-123"});
 assert.equal(response.status,303);
 assert.equal(response.headers.get("location"),"/member","Regular members land in their personal vault.");
 const cookie=response.headers.get("set-cookie").split(";")[0];
 assert.ok(cookie.startsWith("tgl_session="));
 assert.match(response.headers.get("set-cookie"),/HttpOnly/);
 assert.match(response.headers.get("set-cookie"),/SameSite=Strict/);
 // Railway hosts the preview behind HTTPS while NODE_ENV is development.
 // Secure must still be set for its browser session cookie.
 const oldCloud=process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW;
 process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW="1";
 try {
   const secureLogin=await post("/login",{email:"member@example.com",password:"correct-long-password-123"});
   assert.equal(secureLogin.status,303);
   assert.match(secureLogin.headers.get("set-cookie"),/(?:^|; )Secure(?:;|$)/);
   assert.equal(secureLogin.headers.get("strict-transport-security"),"max-age=31536000");
   assert.equal(secureLogin.headers.get("x-robots-tag"),"noindex, nofollow");
 } finally {
   if(oldCloud===undefined)delete process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW;
   else process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW=oldCloud;
 }
 response=await req("/member");
 assert.equal(response.status,303,"Anonymous member dashboard requires login.");
 assert.equal(response.headers.get("location"),"/login");
 response=await req("/member",{headers:{Cookie:cookie}});
 assert.equal(response.status,200);
 let memberMarkup=await response.text();
 assert.match(memberMarkup,/Aloha, Member\./);
 assert.match(memberMarkup,/Unlock the vault/);
 assert.match(memberMarkup,/data-vault-sound/);
 assert.match(memberMarkup,/data-vault-haptics/);
 assert.doesNotMatch(memberMarkup,/add to cart|checkout|purchase now/i);
 const profileCsrf=memberMarkup.match(/name="csrf" value="([^"]+)"/)?.[1];
 assert.ok(profileCsrf);
 response=await post("/member/profile",{csrf:"incorrect",display_name:"Christopher"},cookie);
 assert.equal(response.status,403,"Profile updates require the session CSRF token.");
 response=await post("/member/profile",{csrf:profileCsrf,display_name:"<script>alert(1)</script>"},cookie);
 assert.equal(response.status,400,"Markup cannot become a saved display name.");
 response=await post("/member/profile",{csrf:profileCsrf,display_name:"A".repeat(49)},cookie);
 assert.equal(response.status,400,"Names have a bounded length.");
 response=await post("/member/profile",{csrf:profileCsrf,display_name:"  Christopher   J.  "},cookie);
 assert.equal(response.status,303);
 assert.equal(response.headers.get("location"),"/member?saved=1");
 const savedUser=db.prepare("SELECT email,display_name FROM users WHERE email=?").get("member@example.com");
 assert.equal(savedUser.display_name,"Christopher J.");
 assert.equal(savedUser.email,"member@example.com","Display name cannot change sign-in identity.");
 response=await req("/member?saved=1",{headers:{Cookie:cookie}});
 memberMarkup=await response.text();
 assert.match(memberMarkup,/Aloha, <em>Christopher J\.<\/em>/);
 assert.match(memberMarkup,/Your display name was updated/);
 response=await req("/vault-entry.js");
 assert.equal(response.status,303,"The private sound engine cannot be fetched anonymously.");
 response=await req("/",{headers:{Cookie:cookie}});assert.equal(response.status,200);
 assert.match(await response.text(),/THE GOOD STUFF/);
 response=await req("/assets/shield-logo.webp",{headers:{Cookie:cookie}});assert.equal(response.status,200);
 assert.equal(response.headers.get("content-type"),"image/webp");
 response=await req("/locker-motion.js",{headers:{Cookie:cookie}});assert.equal(response.status,200);
 assert.match(await response.text(),/prefers-reduced-motion/);
 response=await req("/vault-entry.js",{headers:{Cookie:cookie}});
 assert.equal(response.status,200);
 assert.match(await response.text(),/sessionStorage/);
 response=await req("/catalog",{headers:{Cookie:cookie}});
 assert.equal(response.status,200);
 const catalogMarkup=await response.text();
 assert.match(catalogMarkup,/locker-entry-portal/);
 assert.match(catalogMarkup,/Skip intro/);
 assert.match(catalogMarkup,/Replay vault opening/);
 assert.match(catalogMarkup,/\/vault-entry\.js/);
 assert.doesNotMatch(catalogMarkup,/add to cart|checkout|purchase now/i);
 response=await req("/catalog",{headers:{Cookie:cookie}});assert.equal(response.status,200);
 response=await req("/admin",{headers:{Cookie:cookie}});assert.equal(response.status,403);
 db.prepare("UPDATE users SET role='admin' WHERE email=?").run("member@example.com");
 response=await req("/admin",{headers:{Cookie:cookie}});
 assert.equal(response.status,303);assert.equal(response.headers.get("location"),"/admin/mfa");
 response=await req("/admin/mfa",{headers:{Cookie:cookie}});
 let html=await response.text(),csrf=html.match(/name="csrf" value="([^"]+)"/)?.[1];
 assert.ok(csrf);
 response=await post("/admin/mfa/start",{csrf},cookie);
 assert.equal(response.status,303);
 response=await req("/admin/mfa",{headers:{Cookie:cookie}});
 html=await response.text();
 const secret=html.match(/<code>([A-Z2-7]{32})<\/code>/)?.[1];
 assert.ok(secret);
 response=await post("/admin/mfa/confirm",{csrf,code:totpAt(secret)},cookie);
 assert.equal(response.status,200);
 assert.match(await response.text(),/MFA enabled/);
 response=await req("/admin",{headers:{Cookie:cookie}});assert.equal(response.status,200);
 html=await response.text();csrf=html.match(/name="csrf" value="([^"]+)"/)?.[1];
 assert.ok(csrf);
 response=await post("/admin/products",{csrf:"wrong",sku:"DEMO-1",name:"Development Item",category:"Lifestyle"},cookie);
 assert.equal(response.status,403);
 response=await post("/admin/products",{csrf,sku:"DEMO-1",name:"Development Item",category:"Lifestyle",codename:"Ghost Key"},cookie);
 assert.equal(response.status,303);
 const id=db.prepare("SELECT id FROM products WHERE sku=?").get("DEMO-1").id;
 response=await post("/admin/stock",{csrf,product_id:String(id),delta:"10",reason:"Internal stock test"},cookie);
 assert.equal(response.status,303);
 response=await post("/admin/stock",{csrf,product_id:String(id),delta:"-11",reason:"Negative stock test"},cookie);
 assert.equal(response.status,400);
 assert.equal(db.prepare("SELECT SUM(delta) total FROM movements WHERE product_id=?").get(id).total,10);
 response=await req("/catalog",{headers:{Cookie:cookie}});html=await response.text();
 assert.match(html,/Development Item/);assert.match(html,/Ghost Key/);assert.doesNotMatch(html,/buy now|checkout|purchase now/i);
 response=await post("/admin/products/codename",{csrf,product_id:String(id),codename:"Eclipse"},cookie);
 assert.equal(response.status,303);
 assert.equal(db.prepare("SELECT codename FROM products WHERE id=?").get(id).codename,"Eclipse");
 response=await req("/catalog",{headers:{Cookie:cookie}});
 assert.match(await response.text(),/Eclipse/);
 process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW="1";
 try {
   response=await post("/logout",{csrf},cookie);
   assert.equal(response.status,303);
   assert.match(response.headers.get("set-cookie"),/(?:^|; )Secure(?:;|$)/);
 } finally {
   if(oldCloud===undefined)delete process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW;
   else process.env.WORKSHOP_ALLOW_CLOUD_PREVIEW=oldCloud;
 }
 response=await req("/",{headers:{Cookie:cookie}});
 assert.equal(response.status,303,"Logout must revoke the session.");
});
