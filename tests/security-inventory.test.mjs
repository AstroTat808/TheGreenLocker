test("CSV parser accepts quoted line breaks and rejects malformed rows",()=>{
 const rows=parseCsv('sku,name,category,supplier\r\nABC-1,"Concept, ""A""",Lifestyle,""\r\n');
 assert.deepEqual(rows,[{sku:"ABC-1",name:'Concept, "A"',category:"Lifestyle",supplier:""}]);
 assert.throws(()=>parseCsv('sku,name\nX-1,"broken'),/Unclosed/);
 assert.throws(()=>parseCsv("sku,name\nX-1"),/header width/);
});
